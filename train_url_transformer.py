# ── Model ─────────────────────────────────────────────────────────────────────

class URLTransformerClassifier(nn.Module):
    def __init__(self):
        super().__init__()
        self.roberta = RobertaModel.from_pretrained('distilroberta-base')
        h = self.roberta.config.hidden_size
        self.classifier = nn.Sequential(
            nn.Linear(h, 256), nn.ReLU(), nn.Dropout(0.3),
            nn.Linear(256, 64), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(64, 2),   # 0=legitimate, 1=phishing
        )

    def forward(self, input_ids, attention_mask=None):
        out = self.roberta(input_ids=input_ids, attention_mask=attention_mask)
        return self.classifier(out.last_hidden_state[:, 0, :])


# ── Dataset: bulk pre-tokenize once (batched) to keep training GPU-bound ─────

def bulk_tokenize(urls, tokenizer, max_len):
    enc = tokenizer(urls, padding='max_length', truncation=True,
                    max_length=max_len, return_tensors='pt')
    return enc['input_ids'], enc['attention_mask']


# ── Load data ─────────────────────────────────────────────────────────────────

def load_urls() -> pd.DataFrame:
    frames = []

    combined = os.path.join("datasets", "url_data_combined.csv")
    if os.path.exists(combined):
        df = pd.read_csv(combined)[["url", "label"]].dropna()
        df["label"] = df["label"].astype(int)
        df = df[df["label"].isin([0, 1])]
        print(f"  HuggingFace combined: {len(df)} rows")
        frames.append(df)
    else:
        print(f"  '{combined}' not found - run download_url_datasets.py for best results.")

    kaggle = os.path.join("datasets", "dataset_phishing.csv")
    if os.path.exists(kaggle):
        df = pd.read_csv(kaggle)[["url", "status"]].dropna()
        df["label"] = (df["status"].str.lower() == "phishing").astype(int)
        df = df[["url", "label"]]
        print(f"  Kaggle Hannousse:      {len(df)} rows")
        frames.append(df)

    if not frames:
        raise SystemExit("No URL data found. Run download_url_datasets.py first.")

    full = pd.concat(frames, ignore_index=True).drop_duplicates(subset=["url"])
    full = full[full["url"].str.len().between(8, 2048)]
    return full


print("\nLoading URL data...")
full = load_urls()
print(f"Total unique URLs: {len(full)}")
print(full["label"].value_counts().rename({0: "legitimate", 1: "phishing"}).to_string())

urls   = full["url"].tolist()
labels = full["label"].tolist()

X_train, X_test, y_train, y_test = train_test_split(
    urls, labels, test_size=0.15, random_state=42, stratify=labels
)

# Optional cap - applied after split so test set is always representative
if MAX_SAMPLES:
    # Balance classes in training set
    from sklearn.utils import resample
    df_tr = pd.DataFrame({"url": X_train, "label": y_train})
    parts = []
    per_class = MAX_SAMPLES // 2
    for lbl, grp in df_tr.groupby("label"):
        if len(grp) > per_class:
            grp = resample(grp, replace=False, n_samples=per_class, random_state=42)
        parts.append(grp)
    df_tr = pd.concat(parts).sample(frac=1, random_state=42)
    X_train, y_train = df_tr["url"].tolist(), df_tr["label"].tolist()
    print(f"Training set capped at {len(X_train)} samples.")

print(f"Train: {len(X_train)}  |  Test: {len(X_test)}")


# ── Tokenizer + DataLoaders ───────────────────────────────────────────────────

print("\nLoading tokenizer...")
tokenizer = RobertaTokenizer.from_pretrained('distilroberta-base')

print("Bulk-tokenizing URL dataset (this takes a couple of minutes)...")
train_ids, train_mask = bulk_tokenize(X_train, tokenizer, MAX_LEN)
test_ids,  test_mask  = bulk_tokenize(X_test,  tokenizer, MAX_LEN)
train_y = torch.tensor(y_train, dtype=torch.long)
test_y  = torch.tensor(y_test,  dtype=torch.long)
print("Pre-tokenized tensors:", train_ids.shape, test_ids.shape)

train_loader = DataLoader(
    TensorDataset(train_ids, train_mask, train_y),
    batch_size=BATCH_SIZE, shuffle=True, num_workers=0,
)
test_loader = DataLoader(
    TensorDataset(test_ids, test_mask, test_y),
    batch_size=BATCH_SIZE, num_workers=0,
)


# ── Train ─────────────────────────────────────────────────────────────────────

print(f"\n--- Training URLTransformer ({EPOCHS} epochs) ---")

# ── Fail-safe checkpoint/resume helpers ──────────────────────────────────────
_save_path    = os.path.join(SAVE_DIR, "url_transformer.pth")
_resume_path  = os.path.join(SAVE_DIR, "url_transformer_resume.pt")
_CHECKPOINT_EVERY = max(1, len(train_loader) // 6)   # ~6 saves per epoch

def _save_resume(epoch, completed, batch=0):
    ckpt = {
        'model':           model.state_dict(),
        'optimizer':       optimizer.state_dict(),
        'scheduler':       scheduler.state_dict(),
        'epoch':           epoch,
        'batch':           batch,              # absolute batch index inside epoch
        'epoch_completed': completed,
    }
    tmp = _resume_path + ".tmp"
    torch.save(ckpt, tmp)
    os.replace(tmp, _resume_path)

def _save_plain(path):
    tmp = path + ".tmp"
    torch.save(model.state_dict(), tmp)
    os.replace(tmp, path)

model = URLTransformerClassifier().to(DEVICE)

optimizer    = AdamW(model.parameters(), lr=LR)
criterion    = nn.CrossEntropyLoss()
total_steps  = len(train_loader) * EPOCHS
warmup_steps = max(1, total_steps // 10)
scheduler    = get_linear_schedule_with_warmup(
    optimizer, num_warmup_steps=warmup_steps, num_training_steps=total_steps
)

# ── Resume from a previous interrupted run if present ────────────────────────
start_epoch  = 0
resume_batch = 0
if os.path.exists(_resume_path):
    ckpt = torch.load(_resume_path, map_location=DEVICE)
    model.load_state_dict(ckpt['model'])
    optimizer.load_state_dict(ckpt['optimizer'])
    scheduler.load_state_dict(ckpt['scheduler'])
    if ckpt.get('epoch_completed'):
        start_epoch  = ckpt['epoch'] + 1
        resume_batch = 0
    else:
        start_epoch  = ckpt['epoch']
        resume_batch = ckpt.get('batch', 0)
    print(f"[RESUME] Continuing epoch {min(start_epoch + 1, EPOCHS)}/{EPOCHS} "
          f"at batch {resume_batch + 1}/{len(train_loader)}.")

for epoch in range(start_epoch, EPOCHS):
    # Deterministic per-epoch shuffle -> resumed batch order is identical to the
    # interrupted run, so we can skip straight to the exact batch we died at.
    torch.manual_seed(1337 + epoch)
    epoch_loader = iter(train_loader)
    skip = resume_batch if epoch == start_epoch else 0
    for _ in range(skip):
        next(epoch_loader)
    resume_batch = 0

    model.train()
    total_loss = 0
    
    # Print epoch description for PhishNot context
    epoch_desc = epoch_description_url(epoch, EPOCHS)
    print(f"  [INFO] {epoch_desc}")
    
    pbar = tqdm(epoch_loader, total=len(train_loader) - skip,
                desc=f"Epoch {epoch+1}/{EPOCHS}", ncols=100)
    for batch_idx, (ids, mask, lbls) in enumerate(pbar, 1):
        # Check for pause/stop from GUI
        if check_stop():
            _save_resume(epoch, completed=False, batch=batch_idx + skip)
            write_progress("url", epoch, EPOCHS, batch_idx + skip, len(train_loader),
                          loss.item(), status="stopped")
            sys.exit(0)
        if read_control() == 'pause':
            _save_resume(epoch, completed=False, batch=batch_idx + skip)
            write_progress("url", epoch, EPOCHS, batch_idx + skip, len(train_loader),
                          loss.item(), status="paused")
            if wait_if_paused():
                _save_resume(epoch, completed=False, batch=batch_idx + skip)
                write_progress("url", epoch, EPOCHS, batch_idx + skip, len(train_loader),
                              loss.item(), status="stopped")
                sys.exit(0)
            write_progress("url", epoch, EPOCHS, batch_idx + skip, len(train_loader),
                          loss.item(), status="training")

        ids, mask, lbls = ids.to(DEVICE), mask.to(DEVICE), lbls.to(DEVICE)
        optimizer.zero_grad()
        loss = criterion(model(ids, mask), lbls)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        scheduler.step()
        total_loss += loss.item()
        pbar.set_postfix(loss=f"{loss.item():.4f}")
        
        # Write progress every 10 batches for GUI (not every batch to avoid I/O overhead)
        if batch_idx % 10 == 0:
            write_progress("url", epoch, EPOCHS, batch_idx + skip, len(train_loader),
                          loss.item(), status="training",
                          extra={"epoch_desc": epoch_desc})

    avg = total_loss / len(train_loader)
    print(f"  Epoch {epoch+1}/{EPOCHS} - Avg Loss: {avg:.4f}")
    _save_plain(_save_path)
    _save_resume(epoch, completed=True)
    write_progress("url", epoch, EPOCHS, len(train_loader), len(train_loader),
                  avg, status="epoch_complete",
                  extra={"epoch_desc": epoch_desc, "avg_loss": avg})
    print(f"  [OK]  Checkpoint saved -> {_save_path}  (safe to stop here)")


# ── Evaluate ──────────────────────────────────────────────────────────────────

print("\n--- Evaluation ---")
model.eval()
y_pred, y_true, y_scores = [], [], []

with torch.no_grad():
    for ids, mask, lbls in tqdm(test_loader, desc="Evaluating", ncols=100):
        ids, mask = ids.to(DEVICE), mask.to(DEVICE)
        logits = model(ids, mask)
        probs  = torch.softmax(logits, dim=-1).cpu().numpy()
        preds  = np.argmax(probs, axis=1)
        y_pred.extend(preds.tolist())
        y_true.extend(lbls.tolist())
        y_scores.extend(probs[:, 1].tolist())   # phishing probability for AUC

print(f"\nURL Transformer Accuracy : {accuracy_score(y_true, y_pred):.4f}")
print(f"AUC-ROC                  : {roc_auc_score(y_true, y_scores):.4f}")
